/*
 * 四阶递推数列
 * ------------------------------------------------------------
 * 输出数列的前 20 项：
 *   a[0] = 0, a[1] = 0, a[2] = 2, a[3] = 5
 *   a[i] = a[i-1] + a[i-2] + a[i-3] + a[i-4]  (i >= 4)
 *
 * 这是斐波那契数列的推广形式：每一项等于前四项之和。
 * 前几项：0, 0, 2, 5, 7, 14, 28, 54, 103, 199, ...
 *
 * 注意：数据增长很快，第 20 项已接近 int 上限附近，
 *       若需要更多项应改用 long long。
 */

#include <iostream>

using namespace std;

int main() {
    const int N = 20;
    long long a[N] = {0, 0, 2, 5};  // 用 long long 防止后续溢出

    // 从第 4 项开始递推
    for (int i = 4; i < N; ++i) {
        a[i] = a[i - 1] + a[i - 2] + a[i - 3] + a[i - 4];
    }

    cout << "数列前 " << N << " 项：" << endl;
    for (int i = 0; i < N; ++i) {
        cout << a[i];
        if (i != N - 1) {
            cout << ", ";  // 用逗号分隔，末尾不加
        }
    }
    cout << endl;

    return 0;
}
